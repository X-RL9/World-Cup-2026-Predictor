def simulate_match(home_elo, away_elo, neutral=1):
    """Simulate a single match. Returns (home_goals, away_goals)."""
    match_input = pd.DataFrame({
        'const': [1],
        'home_elo': [home_elo],
        'away_elo': [away_elo],
        'neutral': [neutral]
    })
    lambda_home = home_model.predict(match_input)[0]
    lambda_away = away_model.predict(match_input)[0]
    home_goals = stats.poisson.rvs(lambda_home)
    away_goals = stats.poisson.rvs(lambda_away)
    return home_goals, away_goals


def simulate_match_winner(team1, team2):
    """Simulate a match and return the winner. Handles penalties on draw."""
    elo1 = ratings.get(team1, 1000)
    elo2 = ratings.get(team2, 1000)
    g1, g2 = simulate_match(elo1, elo2, neutral=1)
    if g1 > g2:
        return team1
    elif g2 > g1:
        return team2
    else:
        # draw — decide on penalties (50/50 with slight elo bias)
        elo_diff = elo1 - elo2
        p_team1_wins_pens = 1 / (1 + 10**(-elo_diff / 400))
        return team1 if np.random.random() < p_team1_wins_pens else team2

