def simulate_group_stage(fixtures, ratings):
    """Simulate all group stage matches. Returns points table."""
    group_results = {}
    group_matches = fixtures[fixtures['stage'] == 'Group Stage']

    for _, match in group_matches.iterrows():
        team1 = match['team1']
        team2 = match['team2']
        elo1 = ratings.get(team1, 1000)
        elo2 = ratings.get(team2, 1000)
        goals1, goals2 = simulate_match(elo1, elo2, neutral=1)

        if team1 not in group_results:
            group_results[team1] = {'points': 0, 'gd': 0, 'group': match['group']}
        if team2 not in group_results:
            group_results[team2] = {'points': 0, 'gd': 0, 'group': match['group']}

        # goal difference as tiebreaker
        group_results[team1]['gd'] += goals1 - goals2
        group_results[team2]['gd'] += goals2 - goals1

        if goals1 > goals2:
            group_results[team1]['points'] += 3
        elif goals1 == goals2:
            group_results[team1]['points'] += 1
            group_results[team2]['points'] += 1
        else:
            group_results[team2]['points'] += 3

    return group_results


def get_group_qualifiers(group_results):
    """Return top 2 teams from each group, sorted by points then goal difference."""
    df = pd.DataFrame(group_results).T
    df['points'] = df['points'].astype(int)
    df['gd'] = df['gd'].astype(int)

    qualifiers = {}
    for group in df['group'].unique():
        if pd.isna(group):
            continue
        group_teams = df[df['group'] == group].sort_values(
            ['points', 'gd'], ascending=[False, False]
        )
        qualifiers[group] = list(group_teams.index[:2])
    return qualifiers

