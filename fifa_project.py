# STAGE 5 — MONTE CARLO SIMULATION (100,000 runs)
# =============================================================================

def run_monte_carlo(fixtures, ratings, n_simulations=100000):
    """Run n_simulations full tournament simulations. Returns win probability dict."""
    win_counts = defaultdict(int)

    for i in range(n_simulations):
        if i % 10000 == 0:
            print(f"  Simulation {i:,} / {n_simulations:,}...")
        winner = simulate_full_tournament(fixtures, ratings)
        win_counts[winner] += 1

    # convert to probabilities
    win_probs = {team: count / n_simulations for team, count in win_counts.items()}
    return dict(sorted(win_probs.items(), key=lambda x: x[1], reverse=True))

