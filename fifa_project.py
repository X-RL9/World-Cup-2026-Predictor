# STAGE 4 — KNOCKOUT STAGE SIMULATOR
# The 2026 World Cup has a Round of 32, Round of 16, QF, SF, Final
# Group winners/runners-up are seeded into the bracket per FIFA rules
# =============================================================================

def simulate_knockout_round(teams_list):
    """Simulate one knockout round. Takes list of teams, returns list of winners."""
    winners = []
    for i in range(0, len(teams_list), 2):
        if i + 1 < len(teams_list):
            winner = simulate_match_winner(teams_list[i], teams_list[i+1])
            winners.append(winner)
        else:
            winners.append(teams_list[i])
    return winners


def build_r32_bracket(qualifiers):
    """
    Build the Round of 32 bracket from group qualifiers.
    2026 format: 12 groups (A-L), top 2 from each = 24 teams + 8 best third-place = 32 total.
    We simplify by taking top 2 from each group and seeding by group winner/runner-up.
    """
    # winners = positions [0], runners-up = positions [1]
    groups = sorted(qualifiers.keys())
    winners   = [qualifiers[g][0] for g in groups if len(qualifiers[g]) > 0]
    runners_up = [qualifiers[g][1] for g in groups if len(qualifiers[g]) > 1]

    # interleave: W1 vs RU2, W2 vs RU1 style pairing (simplified)
    bracket = []
    for i in range(len(winners)):
        bracket.append(winners[i])
        if i < len(runners_up):
            # pair winner of group i against runner-up of next group
            bracket.append(runners_up[(i + 1) % len(runners_up)])

    return bracket


def simulate_full_tournament(fixtures, ratings):
    """Simulate a full tournament from group stage to final. Returns winner."""
    # group stage
    group_results = simulate_group_stage(fixtures, ratings)
    qualifiers = get_group_qualifiers(group_results)

    # build knockout bracket
    bracket = build_r32_bracket(qualifiers)

    # simulate knockout rounds until one team remains
    while len(bracket) > 1:
        bracket = simulate_knockout_round(bracket)

    return bracket[0]

